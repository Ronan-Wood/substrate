"""Has the vault moved since the index was built — the question `index_version` cannot answer.

Doc 2 §5 and docs/principles.md are precise about what the version stamp buys: it converts SILENT
omission into DETECTABLE omission, and no more. Detection is not freshness. There is no watcher
on this side, so the discipline is pushed onto every consumer, and a consumer with nothing to
compare against cannot exercise it — `index_version` alone tells you what the index was built
from, never that the vault changed underneath it.

This module is the comparison. It walks the scope's vaults and asks, per note, whether the index
still agrees with the disk.

**It reads `source_path`, not `markdown_path`.** Those are different files and the difference is
easy to miss: `markdown_path` is the DERIVED artifact in the disposable index root, which is
regenerated by every compose and always agrees with the index. Checking it would report a green
freshness result over a vault the user had rewritten. `source_path` is the note the user owns.

**It compares `note_sha256`, not `source_sha256`.** The reader (Doc 2 §3b) honours a
`source_sha256` declared in frontmatter — that is how a PDF-derived passage points at the PDF it
came from rather than at itself — so for those notes `source_sha256` is the PDF's and a body edit
leaves it unchanged. `note_sha256` (schema v11) is the note file's own checksum, so every row with
one is checkable. A row without one was written from a run.json older than the field; it falls
back to the old rule and is counted `unverifiable` when that rule cannot see an edit. A freshness
report whose completeness is overstated is the failure this whole project keeps finding; a report
that names the part it could not check is not.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

from substrate.markdown.reader import _SHA256, _parse_frontmatter


def effective_sha_of(data: bytes) -> tuple[str, bool]:
    """The checksum the reader WOULD store for these bytes, and whether it was declared.

    Takes bytes rather than a path so a caller that has already read the file does not read it a
    second time — two reads can straddle a write, leaving the content and the staleness verdict
    describing different versions.

    Mirrors `markdown.reader`: a well-shaped `source_sha256` in frontmatter wins, else the file's
    own checksum. Reusing the rule rather than re-deriving one is what stops this check disagreeing
    with the ingest it is auditing — two checksum rules would make every PDF passage read as
    changed, and a report full of false positives trains its reader to ignore it.
    """
    # Line endings normalized before parsing, exactly as `markdown.reader` and `vault._read_capped`
    # do — the frontmatter regex is LF-anchored, so without this a CRLF-authored note's declared
    # `source_sha256` is invisible here while the reader saw it. That note would then be counted as
    # checked and listed as `changed` forever: permanently STALE on a vault nobody touched, and
    # recomposing would not clear it. The checksum is still taken over the RAW bytes, as the reader
    # takes it.
    text = data.decode("utf-8", errors="replace").replace("\r\n", "\n").replace("\r", "\n")
    front, _ = _parse_frontmatter(text)
    declared = front.get("source_sha256", "")
    if _SHA256.fullmatch(declared):
        return declared, True
    return hashlib.sha256(data).hexdigest(), False


def stale_verdict(raw: bytes, stored_sha: str | None, note_sha: str | None = None) -> bool | None:
    """Whether a note's bytes no longer match what was indexed. One copy, for `expand` on the live
    server and for the agent snapshot's publisher, so the two cannot drift into different
    verdicts about the same note.

    `note_sha` is the row's `note_sha256` and is compared whenever there is one. Without it (a row
    from a run.json older than v11) the old rule applies to the stored checksum, and a DECLARED
    one can still witness a change to the declaration itself — a note whose frontmatter now names a
    different source is `True`. Only a declaration that still matches is `None`: the body behind it
    cannot be seen from here."""
    if note_sha:
        return hashlib.sha256(raw).hexdigest() != note_sha
    sha, declared = effective_sha_of(raw)
    if sha != (stored_sha or ""):
        return True
    return None if declared else False


class NotRegularFile(OSError):
    """`read_bounded` was pointed at a FIFO, a device, a directory — anything but a file."""


class FileTooLarge(OSError):
    """`read_bounded` hit its cap."""


def read_bounded(src: Path, cap: int, *, nofollow: bool = False,
                 dir_fd: int | None = None) -> bytes:
    """A file, bounded by the read ITSELF rather than by a prior check. Raises OSError.

    Opens once, non-blocking so a FIFO cannot stall the open, fstats the DESCRIPTOR it will
    actually read, and reads at most one byte over the cap — so a path swapped for a FIFO or grown
    past the cap after a check cannot get past either bound. A stat-then-read pair described an
    ordering rather than a guarantee.
    """
    import os
    import stat as _stat

    # `dir_fd` opens `src` relative to an already-open folder, so a caller that walked to that
    # folder without following links is not re-resolving the path it checked.
    fd = os.open(src, os.O_RDONLY | os.O_NONBLOCK | (os.O_NOFOLLOW if nofollow else 0),
                 dir_fd=dir_fd)
    try:
        st = os.fstat(fd)
        if not _stat.S_ISREG(st.st_mode):
            raise NotRegularFile(f"{src} is not a regular file")
        # Refused before any byte is read when the file is already over the cap: a sparse file of
        # any size costs nothing to make, and reading cap+1 bytes of it to find out is not free.
        # The read below stays bounded for a file that grows after this.
        if st.st_size > cap:
            raise FileTooLarge(f"{src} exceeds {cap} bytes")
        chunks, size = [], 0
        while size <= cap:
            block = os.read(fd, 1 << 20)
            if not block:
                break
            chunks.append(block)
            size += len(block)
        if size > cap:
            raise FileTooLarge(f"{src} exceeds {cap} bytes")
        return b"".join(chunks)
    finally:
        os.close(fd)


def quarantine_fingerprint(note: Path, meta: Path | None) -> str | None:
    """What a quarantined note was judged on, hashed: the note's bytes, its source's `_meta.md`
    (a passage's class and spine come from there), and the engine's note format
    (`spine.NOTES_VERSION`, which moves when the vocabulary does). Compose stores it and `drift`
    compares it, so a note counts as still quarantined only while none of them has changed. None
    when a file cannot be read or is over the vault's size cap. Every read is bounded by the read
    itself, so a note quarantined for its size (a sparse file of any length) is never read whole,
    by compose or by every `status`; a note still over the cap matches its stored None."""
    from substrate.spine import NOTES_VERSION
    from substrate.vault import _MAX_BYTES

    h = hashlib.sha256(f"notes-v{NOTES_VERSION}\0".encode())
    try:
        for path in (note, meta):
            data = b"" if path is None else read_bounded(path, _MAX_BYTES)
            h.update(len(data).to_bytes(8, "big") + data)
    except OSError:
        return None
    return h.hexdigest()


def drift(store, note_paths: list[Path], quarantined: list[dict] | None = None,
          fingerprint=None) -> dict:
    """Compare the notes on disk against what this index holds.

    `note_paths` is the composed scope's note set (`vault.resolve_scope(...).notes`), so "added"
    means a note the manifest composes that the index does not have — which is the case a caller
    most needs, since it looks identical to a question the corpus simply cannot answer.

    `quarantined` is the index's quarantine record (`IndexStore.quarantined`), and `fingerprint`
    maps a note's path to its `quarantine_fingerprint` now. A note the last compose quarantined,
    whose fingerprint is unchanged, is counted under `quarantined` rather than `added`:
    recomposing would quarantine it again, so it does not make the scope stale. One whose note,
    `_meta.md` or the engine's note format changed since is `added`, because the next compose may
    index it.

    Returns counts plus the paths involved, and `stale` — true if ANY of the three differ.
    """
    # BOTH sides are resolved through the same call. They are written by different code paths —
    # the index stores whatever path ingest was handed, the walk produces whatever rglob yields —
    # and on macOS a temp dir alone differs (`/var/...` vs `/private/var/...`). Comparing them
    # unnormalized reported every single note as simultaneously added AND removed: a drift check
    # that cries wolf on a clean vault is worse than none, because its reader learns to ignore it.
    indexed: dict[str, tuple[str, str | None]] = {
        str(Path(r["source_path"]).resolve()): (r["source_sha256"] or "", r["note_sha256"])
        for r in store.db.execute("SELECT source_path, source_sha256, note_sha256 FROM documents")
    }
    on_disk = {str(p.resolve()): p for p in note_paths}

    added = sorted(set(on_disk) - set(indexed))
    removed = sorted(set(indexed) - set(on_disk))
    held = {str(Path(q["source_path"]).resolve()): q.get("fingerprint")
            for q in quarantined or []}
    still = [a for a in added
             if a in held and fingerprint is not None and fingerprint(on_disk[a]) == held[a]]
    added = [a for a in added if a not in still]

    changed: list[str] = []
    unverifiable = 0
    checked = 0
    unreadable: list[str] = []
    for path_str in sorted(set(indexed) & set(on_disk)):
        try:
            raw = on_disk[path_str].read_bytes()
        except OSError:
            # Indexed, present in the composed set, and unreadable now — neither fresh nor
            # missing, so it gets its own bucket instead of being silently counted as either.
            unreadable.append(path_str)
            continue
        # The ONE verdict `expand` and the agent publisher use, so the three cannot disagree. A
        # changed declaration is `True` there too: the `unverifiable` bucket is for what cannot be
        # checked, not for everything in its neighbourhood.
        verdict = stale_verdict(raw, *indexed[path_str])
        if verdict is None:
            unverifiable += 1
            continue
        checked += 1
        if verdict:
            changed.append(path_str)

    return {
        # `stale` means something DEFINITELY differs. Unreadable notes are a different statement —
        # nothing is known about them — so they get `checkable` rather than being folded in here,
        # where they would be indistinguishable from a detected change. A consumer must read both:
        # `stale: false, checkable: false` is "no change found, and some notes were not examined".
        "stale": bool(added or removed or changed),
        "checkable": not unreadable,
        "added": added,
        "removed": removed,
        "changed": changed,
        "checked": checked,
        # Notes with no `note_sha256` (indexed from a run.json older than v11) whose stored
        # checksum is a DECLARED one (it names a PDF, per Doc 2 §3b), so an edit to the note body
        # cannot be detected from the index alone. Named, not folded into "unchanged" — this count
        # is the honest boundary of what `stale: false` means. Zero after one recompose.
        "unverifiable": unverifiable,
        "unreadable": unreadable,
        # Quarantined notes unchanged since the compose that quarantined them (see above).
        "quarantined": len(still),
    }
