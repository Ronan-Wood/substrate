"""Render results/raw/*.jsonl as the markdown tables in results/RESULTS.md.

usage: .venv/bin/python report.py > results/RESULTS.md

Every condition printed in a header is read from the rows it describes, and refused if the rows disagree.
"""
import json
from pathlib import Path

RAW = Path(__file__).resolve().parent / "results" / "raw"


def rows(name: str) -> list[dict]:
    p = RAW / name
    return [json.loads(line) for line in p.read_text().splitlines()] if p.exists() else []


def last(rs, key) -> dict:
    return {key(r): r for r in rs}


def one(rs, field):
    vals = {json.dumps(r.get(field)) for r in rs}
    assert len(vals) == 1, f"rows disagree on {field}: {vals}"
    return rs[0].get(field)


def f(v, nd=1):
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def size(n):
    return f"{n / 1000:g}k" if n < 1_000_000 else f"{n / 1e6:g}M"


def ef_for(sweep, target):
    return next((s for s in sweep if s["recall"] >= target), None)


def swap(r, key="conditions_start"):
    cnd = r.get(key) or r
    return f"{cnd.get('swap_used_gb')}/{cnd.get('swap_total_gb')}"


def main():
    brute = last(rows("brute.jsonl"), lambda r: r["n"])
    ann_rows = rows("ann.jsonl")
    real_rows = rows("real.jsonl")
    ann = last(ann_rows, lambda r: (r["lib"], r["n"]))
    real = last(real_rows, lambda r: (r["lib"], r["real"]))
    every = ann_rows + real_rows
    k, k_arm = one(every, "k"), one(every, "k_arm")
    ef_f, exact_rows, post_cap = one(every, "ef_filtered"), one(every, "exact_rows"), one(every, "post_cap")

    print("# Vector search at scale — results\n")
    print("Generated by `report.py` from `results/raw/`; conditions are in FINDINGS.md. Times are medians "
          f"of single sequential queries in ms, p95 in brackets; recall is recall@{k}.\n")
    print("**Memory conditions** are recorded per row as swap used / swap total in GB (`swap`). Two Ollama "
          "runners held ~12 GB throughout. Corpora are memory-mapped and warmed before timing. Index RSS is "
          "a process-RSS delta and unreliable under swap pressure; disk MB is the better size figure.\n")

    print("## 1. Brute force (cached float32 matrix, numpy + Accelerate)\n")
    print("All conditions of a row are timed interleaved per query; the raw kernels write into a "
          "preallocated buffer. `mask build` is what a planner pays per query to build the default filter's "
          "mask from cached attribute arrays and find its rows.\n")
    print("| vectors | matrix MB | swap GB | matvec | matvec, 8 threads | matvec, float16 | argpartition | "
          "unfiltered | default filter, mask | default filter, subset | entity filter, subset | mask build |")
    print("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for n in sorted(brute):
        r = brute[n]
        print(f"| {size(n)} | {f(r['matrix_mb'], 0)} | {swap(r)} | {f(r['matvec_ms'], 2)} | "
              f"{f(r.get('threaded_matvec_ms'), 2)} | {f(r.get('f16_matvec_ms'), 1)} | {f(r['argpartition_ms'], 2)} | "
              f"{f(r['none_mask_ms'], 2)} ({f(r['none_mask_p95'], 2)}) | {f(r['default_mask_ms'], 2)} | "
              f"{f(r['default_subset_ms'], 2)} | {f(r['entity_subset_ms'], 3)} | {f(r.get('default_maskbuild_ms'), 2)} |")
    curve_ns = [n for n in sorted(brute) if brute[n].get("subset_curve")]
    if curve_ns:
        cols = sorted({int(c) for n in curve_ns for c in brute[n]["subset_curve"]})
        print("\nExact search over a subset of R random rows (gather + matvec + select), the cost the "
              f"planner's exact path pays; the planner goes exact at ≤ {exact_rows:,} rows.\n")
        print("| vectors | " + " | ".join(f"{c:,} rows" for c in cols) + " |")
        print("|---|" + "---|" * len(cols))
        for n in curve_ns:
            cv = brute[n]["subset_curve"]
            print(f"| {size(n)} | " + " | ".join(f(cv.get(str(c)), 2) for c in cols) + " |")

    print("\n## 2. ANN, unfiltered: build, size, reachability, and the latency to reach a recall\n")
    print("ef is the search beam (`efSearch` / `expansion_search`). `ms@0.95` is the latency at the smallest "
          "swept ef whose recall ≥ 0.95. `self-miss` is the share of 1,000 sampled corpus rows that do not "
          "find themselves at the widest ef: unreachable nodes, which cap recall at any ef. sqlite-vec is exact.\n")
    print("`load s` is a warm-cache load (the file was just written). Marked † it is a memory-mapped view "
          "(usearch), which reads nothing at load time, so the view's own median query time at ef 128 is "
          "given beside it. Latency and recall columns are from the in-memory index; the ef sweep is "
          "interleaved per query. `@k30` is unfiltered recall@30 at the filtered runs' ef, the baseline "
          "for the k = 30 filtered table. Build threads are 12 unless the label ends `_t1`.\n")
    print("| library | M / efc | vectors | build s | disk MB | load s | self-miss | recall, ef 16 / 64 / 128 / 512 | "
          "best recall (ef, ms) | ms@0.95 (ef) | ms@0.99 (ef) | @k30 | brute ms | swap GB start→end |")
    print("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for (lib, n) in sorted(ann, key=lambda t: (t[1], t[0])):
        r = ann[(lib, n)]
        sw = {s["ef"]: s for s in r["sweep"]}
        rec = " / ".join(f(sw[e]["recall"], 3) for e in (16, 64, 128, 512) if e in sw) or f(r["sweep"][0]["recall"], 3)
        top = r["sweep"][-1]
        cell = lambda s: f"{f(s['ms'], 2)} ({s['ef']})" if s else "not reached"
        sm = r.get("self_miss")
        u30 = (r.get("unfiltered_at_k_arm") or {}).get("recall")
        load = f(r.get('load_s'), 2) + (f" † (view query {f(r.get('view_query_ms'), 2)} ms)" if r.get("load_is_mmap") else "")
        print(f"| {lib} | {r['M']} / {r['ef_construction']} | {size(n)} | {f(r['build_s'])} | {f(r['disk_mb'], 0)} | "
              f"{load} | {'—' if sm is None else f'{sm:.1%}'} | {rec} | "
              f"{f(top['recall'], 4)} ({top['ef']}, {f(top['ms'], 2)}) | {cell(ef_for(r['sweep'], 0.95))} | "
              f"{cell(ef_for(r['sweep'], 0.99))} | {f(u30, 3)} | {f(brute.get(n, {}).get('none_mask_ms'), 2)} | "
              f"{swap(r)}→{swap(r, 'conditions_end')} |")

    def trip(d):
        if not d:
            return "—"
        s = f"{f(d['recall'], 3)} / {d['short']} / {f(d['ms'], 2)}"
        if d.get("raised"):
            s += f" ({d['raised']} raised)"
        return s + (f" ⚠ {d['violations']} viol" if d.get("violations") else "")

    print(f"\n## 3. Filtered search at ef = {ef_f}\n")
    print(f"Each cell is recall / short / ms. `short` = queries (of `queries`) that returned fewer than "
          f"min(k, rows passing the filter), a correctness failure under substrate's every-arm rule. `post` asks "
          f"for min(k / selectivity × 2, {post_cap:,}) neighbours. `planned` goes exact at ≤ {exact_rows:,} rows "
          "passing, else post-filters with an exact fallback whenever that comes back short, so it cannot be "
          "short by construction; its paths column counts exact·ann·fallback, and `ann-path recall` is its "
          "recall over the queries that took the ANN path alone. Every strategy builds the filter's mask per "
          "query inside its timing (native also builds its bitmap or callback); sqlite-vec's filter is SQL over "
          "its own tables. Strategies are interleaved per query. `(N raised)` = hnswlib calls that raised "
          "because fewer than k were found; the API returns nothing for those. Recall is tie-aware: a row "
          "scoring at least the k-th true score counts as a hit.\n")
    for kk in (k, k_arm):
        print(f"\n### k = {kk}{' (what the vector arm requests: k × 3)' if kk == k_arm else ''}\n")
        print("| library | vectors | queries | filter | rows passing | native | post | planned | planned paths | "
              "ann-path recall (unfiltered at the same k and ef) |")
        print("|---|---|---|---|---|---|---|---|---|---|")
        for (lib, n) in sorted(ann, key=lambda t: (t[1], t[0])):
            r = ann[(lib, n)]
            for fname, row in r["filters"].items():
                pl = row.get(f"planned@{kk}")
                paths = f"{pl['exact']}·{pl['ann']}·{pl['fallback']}" if pl else "—"
                print(f"| {lib} | {size(n)} | {r['queries']} | {fname} | {row['allowed']:,} | "
                      f"{trip(row.get(f'native@{kk}'))} | {trip(row.get(f'post@{kk}'))} | {trip(pl)} | {paths} | "
                      f"{f((pl or {}).get('recall_ann_path'), 3)}"
                      + (f" ({f(pl['unfiltered_same_ef'], 3)} at ef {pl['ef_used']})" if pl and 'unfiltered_same_ef' in pl else "")
                      + " |")

    if real:
        print("\n## 4. Real vectors (scratch copies, read-only), passage chunks only\n")
        print("Queries are held-out passage chunks (up to 200 per scope). `short (own row passes)` splits the "
              "short count: the second number is the short answers among queries whose own row passes the "
              "filter; the rest come from queries drawn out of the region the filter excludes. The synthetic "
              "rows are the 10k corpus for comparison.\n")
        print("| library | corpus | vectors | queries | self-miss | recall, ef 16 / 32 / 64 / 128 |")
        print("|---|---|---|---|---|---|")
        comp = [(lib, sc, real[(lib, sc)]) for (lib, sc) in sorted(real)]
        comp += [(lib, "synthetic 10k", ann[(lib, n)]) for (lib, n) in sorted(ann)
                 if n == 10000 and lib in {l for l, _ in real}]
        for lib, sc, r in sorted(comp, key=lambda t: (t[0], t[1])):
            sw = {s["ef"]: s for s in r["sweep"]}
            sm = r.get("self_miss")
            print(f"| {lib} | {sc} | {r['n']:,} | {r['queries']} | {'—' if sm is None else f'{sm:.1%}'} | "
                  + " / ".join(f(sw[e]["recall"], 3) for e in (16, 32, 64, 128)) + " |")
        for kk in (k, k_arm):
            print(f"\n**Filtered, real, k = {kk}.** Each cell: recall / short (own row passes) / ms.\n")
            print("| library | corpus | filter | rows passing | queries passing | native | post | planned |")
            print("|---|---|---|---|---|---|---|---|")
            for (lib, sc) in sorted(real):
                r = real[(lib, sc)]
                for fname, row in r["filters"].items():
                    def rc(d):
                        if not d:
                            return "n/a"
                        return f"{f(d['recall'], 3)} / {d['short']} ({d['short_query_passes']}) / {f(d['ms'], 2)}"
                    qp = (row.get(f"post@{kk}") or {}).get("queries_passing")
                    print(f"| {lib} | {sc} | {fname} | {row['allowed']:,} | {qp} | {rc(row.get(f'native@{kk}'))} | "
                          f"{rc(row.get(f'post@{kk}'))} | {rc(row.get(f'planned@{kk}'))} |")


if __name__ == "__main__":
    main()
